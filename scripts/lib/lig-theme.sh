# Generate lig's popup colours (~/.config/lig/colors.toml) from the terminal
# theme.
#
# lig (github.com/KevenGoncalves/lig) reads a single config file and has no
# include directive, so ~/.config/zsh/lig-theme.zsh concatenates the
# chezmoi-managed ~/.config/lig/base.toml with this generated [colors] table
# into config.toml. Without colors.toml lig falls back to the `terminal`
# theme set in base.toml (ANSI colours, which already follow the terminal).
#
# Mapping, from the Ghostty theme file (light and dark alike, since every
# colour is derived from the theme's own background and foreground):
#   bg, border_bg, fg     "default"  the popup sits on the terminal itself
#   selected_bg           selection-background (the theme's own highlight);
#                         theme foreground at 20% over the background if the
#                         theme has none or it is nearly the background
#   selected_fg           selection-foreground, else foreground; 4.5:1 on selected_bg
#   selected_description_fg  selected_fg faded 25% toward selected_bg; 4.5:1
#   description_fg, info_fg  foreground faded 40% toward the background; 4.5:1
#   match_fg              ANSI blue (palette 4), else selected_fg; 4.5:1 on the
#                         background (lig draws matched letters on the selected
#                         row in selected_fg, so only plain rows use match_fg)
#   border_fg             foreground faded 60%; 3:1 (non-text graphic)
#   scrollbar_fg/thumb    foreground at 15% / faded 50% (thumb 3:1)
# Text that falls short of its contrast target is pushed toward black or white.

# shellcheck source=awk-colour.sh
source "$(dirname -- "${BASH_SOURCE[0]}")/awk-colour.sh"

lig_theme_error=""

# lig_generate_colors <ghostty-theme-file> <destination>
lig_generate_colors() {
  local theme_file="$1"
  local destination="$2"
  local destination_dir temporary colors

  lig_theme_error=""

  if [[ ! -f "$theme_file" ]]; then
    lig_theme_error="terminal theme not found: $theme_file"
    return 1
  fi

  if ! colors=$(lig_colors_from_theme "$theme_file"); then
    lig_theme_error="$theme_file lacks a background or foreground"
    return 1
  fi

  destination_dir=$(dirname -- "$destination")
  mkdir -p -- "$destination_dir" || {
    lig_theme_error="cannot create $destination_dir"
    return 1
  }
  temporary=$(mktemp "$destination_dir/.colors.XXXXXX") || {
    lig_theme_error="cannot write in $destination_dir"
    return 1
  }
  printf '%s\n' "$colors" >"$temporary" && mv -f -- "$temporary" "$destination" || {
    rm -f -- "$temporary"
    lig_theme_error="cannot write $destination"
    return 1
  }
}

# Print the [colors] table for a Ghostty theme file; exit non-zero when the
# background or foreground is missing. Pure: reads the file, writes stdout.
lig_colors_from_theme() {
  awk "$awk_colour_functions"'
    function value(line) { sub(/^[^=]*=[ \t]*/, "", line); sub(/[ \t]+$/, "", line); return line }

    /^[ \t]*background[ \t]*=/ { bg = norm(value($0)) }
    /^[ \t]*foreground[ \t]*=/ { fg = norm(value($0)) }
    /^[ \t]*selection-background[ \t]*=/ { selbg = norm(value($0)) }
    /^[ \t]*selection-foreground[ \t]*=/ { selfg = norm(value($0)) }
    /^[ \t]*palette[ \t]*=[ \t]*4[ \t]*=/ { v = value($0); sub(/^4[ \t]*=[ \t]*/, "", v); blue = norm(v) }

    END {
      if (bg == "" || fg == "") exit 1
      if (selbg == "" || ratio(selbg, bg) < 1.15) selbg = mix(fg, bg, 0.20)
      if (selfg == "") selfg = fg
      selfg = legible(selfg, selbg)
      if (blue == "") blue = selfg
      quiet = legible(mix(fg, bg, 0.60), bg)

      print "# Generated by set-theme (scripts/lib/lig-theme.sh); edits are overwritten."
      print "[colors]"
      print "bg = \"default\""
      print "fg = \"default\""
      print "border_bg = \"default\""
      printf "selected_bg = \"#%s\"\n", selbg
      printf "selected_fg = \"#%s\"\n", selfg
      printf "selected_description_fg = \"#%s\"\n", legible(mix(selfg, selbg, 0.75), selbg)
      printf "description_fg = \"#%s\"\n", quiet
      printf "info_fg = \"#%s\"\n", quiet
      printf "match_fg = \"#%s\"\n", legible(blue, bg)
      printf "border_fg = \"#%s\"\n", legible_to(mix(fg, bg, 0.40), bg, 3)
      printf "scrollbar_fg = \"#%s\"\n", mix(fg, bg, 0.15)
      printf "scrollbar_thumb = \"#%s\"\n", legible_to(mix(fg, bg, 0.50), bg, 3)
    }
  ' "$1"
}
